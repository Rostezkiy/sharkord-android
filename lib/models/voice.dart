import 'parse.dart';

class VoiceUserState {
  const VoiceUserState({
    this.micMuted = false,
    this.soundMuted = false,
    this.webcamEnabled = false,
    this.sharingScreen = false,
  });

  final bool micMuted;
  final bool soundMuted;
  final bool webcamEnabled;
  final bool sharingScreen;

  factory VoiceUserState.fromJson(Map<String, dynamic> json) => VoiceUserState(
    micMuted: asBool(json['micMuted']),
    soundMuted: asBool(json['soundMuted']),
    webcamEnabled: asBool(json['webcamEnabled']),
    sharingScreen: asBool(json['sharingScreen']),
  );
}

/// the wire values of a stream, exactly as `StreamKind` in the shared package.
enum StreamKind {
  audio('audio'),
  video('video'),
  screen('screen'),
  screenAudio('screen_audio'),
  externalVideo('external_video'),
  externalAudio('external_audio');

  const StreamKind(this.wire);

  final String wire;

  static StreamKind fromWire(Object? value) {
    final raw = asString(value);

    return StreamKind.values.firstWhere(
      (kind) => kind.wire == raw,
      orElse: () => StreamKind.audio,
    );
  }

  /// mediasoup only knows two media kinds, the server maps the rest onto them.
  bool get isAudio =>
      this == StreamKind.audio ||
      this == StreamKind.screenAudio ||
      this == StreamKind.externalAudio;
}

/// the answer to `voice.getProducers`: who is publishing what in the channel.
class VoiceProducerIds {
  const VoiceProducerIds({
    this.audio = const <int>[],
    this.video = const <int>[],
    this.screen = const <int>[],
    this.screenAudio = const <int>[],
    this.externalStreams = const <int>[],
  });

  static const VoiceProducerIds empty = VoiceProducerIds();

  final List<int> audio;
  final List<int> video;
  final List<int> screen;
  final List<int> screenAudio;
  final List<int> externalStreams;

  factory VoiceProducerIds.fromJson(Map<String, dynamic> json) =>
      VoiceProducerIds(
        audio: asIntList(json['remoteAudioIds']),
        video: asIntList(json['remoteVideoIds']),
        screen: asIntList(json['remoteScreenIds']),
        screenAudio: asIntList(json['remoteScreenAudioIds']),
        externalStreams: asIntList(json['remoteExternalStreamIds']),
      );
}

/// the answer to `voice.consume`: everything a mediasoup consumer needs, all of
/// it generated by the server's router.
class VoiceConsumerParams {
  const VoiceConsumerParams({
    required this.consumerId,
    required this.producerId,
    required this.kind,
    required this.rtpParameters,
  });

  final String consumerId;
  final String producerId;
  final StreamKind kind;
  final Map<String, dynamic> rtpParameters;

  factory VoiceConsumerParams.fromJson(Map<String, dynamic> json) =>
      VoiceConsumerParams(
        consumerId: asString(json['consumerId']),
        producerId: asString(json['producerId']),
        kind: StreamKind.fromWire(json['consumerKind']),
        rtpParameters: asMap(json['consumerRtpParameters']),
      );
}

/// a producer appeared or disappeared in the voice channel this client is in.
class VoiceProducerEvent {
  const VoiceProducerEvent({
    required this.channelId,
    required this.remoteId,
    required this.kind,
  });

  final int channelId;
  final int remoteId;
  final StreamKind kind;

  factory VoiceProducerEvent.fromJson(Map<String, dynamic> json) =>
      VoiceProducerEvent(
        channelId: asInt(json['channelId']),
        remoteId: asInt(json['remoteId']),
        kind: StreamKind.fromWire(json['kind']),
      );
}

/// the shape of `voiceMap` in the join payload: channel id to the voice state of
/// every user currently in that channel.
class VoiceMap {
  const VoiceMap(this.byChannel);

  final Map<int, Map<int, VoiceUserState>> byChannel;

  static const VoiceMap empty = VoiceMap(<int, Map<int, VoiceUserState>>{});

  factory VoiceMap.fromJson(Object? json) {
    final raw = asMap(json);
    final result = <int, Map<int, VoiceUserState>>{};

    for (final entry in raw.entries) {
      final channelId = int.tryParse(entry.key);
      if (channelId == null) continue;

      final users = asMap(asMap(entry.value)['users']);
      final states = <int, VoiceUserState>{};

      for (final user in users.entries) {
        final userId = int.tryParse(user.key);
        if (userId == null) continue;

        states[userId] = VoiceUserState.fromJson(asMap(user.value));
      }

      result[channelId] = states;
    }

    return VoiceMap(result);
  }

  Map<int, VoiceUserState> usersIn(int channelId) =>
      byChannel[channelId] ?? const <int, VoiceUserState>{};

  int countIn(int channelId) => usersIn(channelId).length;

  VoiceMap withUser(int channelId, int userId, VoiceUserState state) {
    final next = <int, Map<int, VoiceUserState>>{
      for (final entry in byChannel.entries) entry.key: {...entry.value},
    };

    next.putIfAbsent(channelId, () => <int, VoiceUserState>{})[userId] = state;

    return VoiceMap(next);
  }

  VoiceMap withoutUser(int channelId, int userId) {
    final next = <int, Map<int, VoiceUserState>>{
      for (final entry in byChannel.entries) entry.key: {...entry.value},
    };

    next[channelId]?.remove(userId);

    return VoiceMap(next);
  }

  VoiceMap updateState(int channelId, int userId, VoiceUserState state) {
    if (!usersIn(channelId).containsKey(userId)) return this;

    return withUser(channelId, userId, state);
  }
}
